func seedMenuCategories(ctx context.Context, tx *ent.Tx) error {
	for _, cat := range menuCategories {
		catID := categoryUUID(cat.Slug)

		_, err := tx.MenuCategory.Get(ctx, catID)
		if err == nil {
			if cat.IconURL != "" {
				_, _ = tx.MenuCategory.UpdateOneID(catID).SetImageURL(cat.IconURL).Save(ctx)
			}
			continue
		}
		if !ent.IsNotFound(err) {
			return fmt.Errorf("check category %s: %w", cat.Slug, err)
		}

		create := tx.MenuCategory.Create().
			SetID(catID).
			SetName(cat.Name).
			SetDescription(cat.Description).
			SetDisplayOrder(cat.DisplayOrder).
			SetIsActive(true)
		if cat.IconURL != "" {
			create = create.SetImageURL(cat.IconURL)
		}
		_, err = create.Save(ctx)
		if err != nil {
			return fmt.Errorf("create category %s: %w", cat.Slug, err)
		}
		log.Printf("category created: %s", cat.Name)
	}
	return nil
}

func seedMenuItems(ctx context.Context, tx *ent.Tx, tenantID, cafeID uuid.UUID) error {
	catIDMap := make(map[string]uuid.UUID, len(menuCategories))
	for _, cat := range menuCategories {
		catIDMap[cat.Slug] = categoryUUID(cat.Slug)
	}

	for _, item := range menuItems {
		itemID := menuItemUUID("urban-loft", item.SKU)

		exists, err := tx.MenuItem.Query().
			Where(menuitem.ID(itemID)).
			Exist(ctx)
		if err != nil {
			return fmt.Errorf("check menu item %s: %w", item.SKU, err)
		}

		catID, ok := catIDMap[item.CategorySlug]
		if !ok {
			return fmt.Errorf("unknown category slug %q for SKU %s", item.CategorySlug, item.SKU)
		}

		imgURL := item.ImageURL
		if imgURL == "" {
			imgURL = mediaMenuPlaceholder
		}

		if exists {
			// Update existing item image and category (in case it changed)
			_, err = tx.MenuItem.UpdateOneID(itemID).
				SetCafeID(cafeID).
				SetCategoryID(catID).
				SetImageURL(imgURL).
				Save(ctx)
			if err != nil {
				return fmt.Errorf("update menu item %s: %w", item.SKU, err)
			}
			continue
		}
		_, err = tx.MenuItem.Create().
			SetID(itemID).
			SetTenantID(tenantID).
			SetCafeID(cafeID).
			SetCategoryID(catID).
			SetName(item.Name).
			SetDescription(item.Description).
			SetBasePrice(item.BasePrice).
			SetCurrency("KES").
			SetIsAvailable(true).
			SetLeadTimeMinutes(item.LeadTimeMinutes).
			SetSku(item.SKU).
			SetDisplayOrder(item.DisplayOrder).
			SetImageURL(imgURL).
			Save(ctx)
		if err != nil {
			return fmt.Errorf("create menu item %s (%s): %w", item.SKU, item.Name, err)
		}
		log.Printf("menu item created: %s — %s", item.SKU, item.Name)
	}
	return nil
}
